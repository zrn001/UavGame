# -*- coding: utf-8 -*-
"""
================================================================================
                        脑控车系统 · 共享配置文件
================================================================================

这是整个系统的【唯一配置入口】。离线训练 (offline_TRCA_train.py) 和
在线分类 (TRCA_BrainCar.py) 都从这里读取配置，保证两边参数永远一致。

你平时只需要改两个地方（下面用 ┏━━┓ 框出来了）：
  1. BAD_CHANNELS     —— 每次采集后，把坏导联填进去
  2. CLASSIFY_WINDOW  —— 调试时，改分类窗长（0.5 / 1.0 / 2.0 秒）

改完直接重新跑离线训练 + 在线分类即可，不用动其它任何文件。
================================================================================
"""

import numpy as np


# ============================================================================
# 【固定】32 通道主列表 —— 放大器 TCP / BDF 文件的物理通道顺序
# 一般不用改。只有当你换了脑电帽、通道顺序变了才需要改这里。
# ============================================================================
FULL_CHANNELS = [
'PO5', 'PO3', 'POZ', 'PO4', 'PO6', 
'O1', 'OZ', 'O2','PO7','PO8',
'PZ','P1','P2','P3','P4',
'P5','P6','P7','P8'
]  # 共 32 个导联，索引 0~31

# FULL_CHANNELS = [
#     'PZ',  'OZ',  'FC2', 'O2',  'C4',  'FC6', 'PO6', 'T8',
#     'P8',  'F8',  'CP6', 'P4',  'F4',  'CP2', 'FP2', 'POZ',
#     'F7',  'P7',  'CP5', 'F3',  'P3',  'FC1', 'O1',  'FZ',
#     'CZ',  'FPZ', 'CP1', 'FP1', 'C3',  'PO5', 'FC5', 'T7',
# ]  # 共 32 个导联，索引 0~31

# ============================================================================
#                        ★★★ 需要你改的地方 (1/2) ★★★
# ============================================================================
# ┏━━━━━━━━━━━━━━━━━ 【坏导联：每次采集后在这里改】━━━━━━━━━━━━━━━━━┓
BAD_CHANNELS = []       # 填坏导联的名字，可多个：['FZ', 'P4', 'T8']
#                           # 如果这次没有坏导联，就写空列表：[]
# ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛


# ============================================================================
#                        ★★★ 需要你改的地方 (2/2) ★★★
# ============================================================================
# ┏━━━━━━━━━━━━━━━━━ 【分类窗长：调试时在这里改】━━━━━━━━━━━━━━━━━┓
CLASSIFY_WINDOW = 1.0       # 分类时间窗，单位：秒。常用 0.5 / 1.0 / 2.0
#                           # 诊断实验结论：1.0s 准确率远优于 0.5s / 0.8s
#                           # 改完后必须【重新跑离线训练】再跑在线！
# ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛
VISUAL_DELAY = 0.14         # 视觉延迟补偿（秒），一般固定 0.14，不用动


# ============================================================================
# 【自动计算】以下都是根据上面配置自动推导的，不用手动改
# ============================================================================

# 好导联名字列表（从主列表里剔除坏导联，保持主列表原顺序）
GOOD_CHANNELS = [ch for ch in FULL_CHANNELS if ch not in BAD_CHANNELS]

# 好导联在主列表中的 0-based 索引（在线 ch_ind 用；顺序与 GOOD_CHANNELS 一致）
GOOD_CH_INDEX = np.array(
     [51, 52, 53, 54, 55, 57, 58, 59, 50, 56, 45, 44, 46, 43, 47, 42, 48, 41, 49],
    dtype=int,
)

# 分类时间窗 [tmin, tmax]（离线 tmin/tmax 和在线 stim_interval 共用）
STIM_INTERVAL = [VISUAL_DELAY, VISUAL_DELAY + CLASSIFY_WINDOW]


# ---- 启动自检：确认坏导联名字都合法 ----
_unknown = [ch for ch in BAD_CHANNELS if ch not in FULL_CHANNELS]
if _unknown:
    raise ValueError(
        f"BAD_CHANNELS 里有未知导联名 {_unknown}，"
        f"它不在 FULL_CHANNELS 主列表里。请检查拼写（注意大小写）。"
    )


def print_config():
    """打印当前生效的配置，方便运行时核对。"""
    print("=" * 60)
    print("            共享配置 config_channels.py 当前生效值")
    print("=" * 60)
    print(f"  分类窗长 CLASSIFY_WINDOW : {CLASSIFY_WINDOW} 秒")
    print(f"  时间窗   STIM_INTERVAL   : {STIM_INTERVAL}  (tmin, tmax)")
    print(f"  坏导联   BAD_CHANNELS    : {BAD_CHANNELS if BAD_CHANNELS else '（无）'}")
    print(f"  全部导联 FULL_CHANNELS   : {len(FULL_CHANNELS)} 个")
    print(f"  有效导联 GOOD_CHANNELS   : {len(GOOD_CHANNELS)} 个")
    print(f"  有效导联索引 GOOD_CH_INDEX: {GOOD_CH_INDEX.tolist()}")
    print(f"  有效导联名单             : {GOOD_CHANNELS}")
    print("=" * 60)


if __name__ == '__main__':
    print_config()
